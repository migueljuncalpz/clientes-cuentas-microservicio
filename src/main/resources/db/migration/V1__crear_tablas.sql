CREATE TABLE clientes (
    dni VARCHAR(9) PRIMARY KEY,
    nombre VARCHAR(255),
    apellido1 VARCHAR(255),
    apellido2 VARCHAR(255),
    fecha_nacimiento DATE
);

CREATE TABLE cuentas_bancarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 8) PRIMARY KEY,
    dni_cliente VARCHAR(9) NOT NULL,
    tipo_cuenta VARCHAR(16) NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_cuenta_cliente FOREIGN KEY (dni_cliente) REFERENCES clientes(dni),
    CONSTRAINT ck_saldo_no_negativo CHECK (total >= 0),
    CONSTRAINT ck_tipo_cuenta CHECK (tipo_cuenta IN ('NORMAL', 'PREMIUM', 'JUNIOR'))
);

CREATE INDEX idx_cuentas_cliente ON cuentas_bancarias(dni_cliente);
